import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { _electron as electron, expect } from 'playwright/test'
import { electronLaunchOptions } from './electron-launch.mjs'

mkdirSync(resolve('tests/.tmp'), { recursive: true })
const dataDir = mkdtempSync(resolve('tests/.tmp/incident-workflow-'))
const app = await electron.launch(electronLaunchOptions({ dataDir, packagedExecutable: process.env.OMNIS_E2E_EXE }))
const checks = [], errors = []
let page
try {
  assert.equal(resolve(await app.evaluate(({ app }) => app.getPath('userData'))), dataDir)
  page = await app.firstWindow()
  page.setDefaultTimeout(15000)
  page.on('pageerror', e => errors.push(e.message))
  page.on('dialog', d => d.accept())
  const raw = (channel, payload = {}) => page.evaluate(([c,p]) => window.omnis.invoke(c,p), [channel,payload])
  const invoke = async (channel, payload = {}) => {
    const r = await raw(channel,payload)
    assert.equal(r.ok,true,`${channel}: ${JSON.stringify(r)}`)
    return r.data
  }
  const login = async (username, role) => {
    await page.getByRole('radio',{name:role==='ADMIN'?'관리자':'사용자',exact:true}).click()
    await page.getByRole('textbox',{name:'아이디',exact:true}).fill(username)
    await page.getByRole('textbox',{name:'비밀번호',exact:true}).fill('Demo!2026')
    await page.getByRole('button',{name:role==='ADMIN'?'관리자 로그인':'사용자 로그인',exact:true}).click()
    await page.getByRole('link',{name:'고장관리',exact:true}).click()
    assert.equal((await invoke('auth:me')).role,role)
  }
  const record = (name, data) => { checks.push({name,...data}); console.log(name) }
  const choose = async (scope, label, name) => {
    await scope.getByRole('combobox',{name:label,exact:true}).click()
    await page.getByRole('option',{name,exact:true}).click()
  }
  const title = '가상 고장 접수부터 종결까지 업무 흐름 검증'
  const openDetail = async () => {
    await page.getByPlaceholder('제목 또는 접수번호 검색').fill(title)
    await page.getByRole('row').filter({hasText:title}).getByRole('button',{name:'상세',exact:true}).click()
    return page.getByRole('dialog')
  }
  const screenshot = async name => {
    for(const [width,height] of [[1366,768],[1920,1080]]) {
      await page.setViewportSize({width,height})
      if(name.endsWith('history'))await page.locator('.MuiDialogContent-root:visible').evaluateAll(nodes=>nodes.forEach(n=>{n.scrollTop=n.scrollHeight}))
      await page.screenshot({path:resolve(dataDir,`${name}-${width}.png`),animations:'disabled'})
      assert.equal(await page.locator('.MuiDialogContent-root:visible').evaluateAll(nodes=>nodes.some(n=>n.scrollWidth>n.clientWidth+1)),false,'Dialog must not overflow horizontally')
    }
  }
  await login('demo_admin','ADMIN')
  const teams = await invoke('control:teams'), users = await invoke('users:list')
  const wire = teams.find(t=>t.code==='TEAM-WIRE'), radio = teams.find(t=>t.code==='TEAM-RADIO')
  const legacy=(await invoke('incidents:list')).find(row=>row.status==='ASSIGNED'&&!row.team_id)
  assert.ok(legacy)
  const incompleteStart=await raw('incidents:updateStatus',{id:legacy.id,status:'REMOTE_IN_PROGRESS'})
  assert.equal(incompleteStart.ok,false);assert.match(incompleteStart.error.message,/모두 선택/)
  const early=await invoke('incidents:create',{title:'가상 단계별 필드 검증',category:'기반통신',severity:'NORMAL',description:'분류 단계에서 조치 결과와 사용자 확인을 미리 저장할 수 없습니다.'})
  await invoke('incidents:updateStatus',{id:early.id,status:'TRIAGED',resolutionMode:'ON_SITE',cause:'미리 저장 금지',actionSummary:'미리 저장 금지',recurrenceRisk:'HIGH',userConfirmed:true})
  const earlyRow=await invoke('incidents:get',{id:early.id})
  assert.deepEqual([earlyRow.resolution_mode,earlyRow.cause,earlyRow.action_summary,earlyRow.recurrence_risk,earlyRow.user_confirmed],[null,null,null,null,0])
  const maintainer = users.find(u=>u.username==='demo_4'), admin = await invoke('auth:me')
  await page.getByRole('button',{name:'신규 고장 접수',exact:true}).click()
  let dialog=page.getByRole('dialog')
  await dialog.getByRole('textbox',{name:'제목',exact:true}).fill(title)
  await dialog.getByRole('textbox',{name:'장애 증상',exact:true}).fill('가상 네트워크 교환기의 간헐적인 연결 중단을 검증합니다.')
  await dialog.getByRole('textbox',{name:'요청부서',exact:true}).fill('가상 요청부서')
  await dialog.getByRole('button',{name:'저장',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  const initial=(await invoke('incidents:list',{search:title}))[0]
  const get=()=>invoke('incidents:get',{id:initial.id})
  const history=()=>invoke('incidents:getEvents',{id:initial.id})
  assert.equal(initial.status,'RECEIVED');assert.equal(initial.team_id,null);assert.equal(initial.assigned_to,null)
  for(const [channel,payload] of [['incidents:assignTeam',{teamId:wire.id,userId:maintainer.id}],['incidents:assign',{userId:maintainer.id}]]) {
    const r=await raw(channel,{id:initial.id,...payload})
    assert.equal(r.ok,false);assert.match(r.error.message,/분류/)
  }
  await invoke('incidents:applyAi',{id:initial.id,category:'기반통신',severity:'NORMAL',teamId:wire.id,rationale:'가상 추천 검토',confidence:.8})
  await invoke('incidents:update',{id:initial.id,title,category:'기반통신',severity:'NORMAL',description:initial.description,department:'가상 요청부서'})
  assert.deepEqual([(await get()).status,(await get()).team_id,(await get()).assigned_to],['RECEIVED',null,null])
  dialog=await openDetail()
  await expect(dialog.getByRole('combobox',{name:'조치부서',exact:true})).toHaveCount(0)
  await expect(dialog.locator('.timeline-step').filter({hasText:'접수 → 접수'})).toHaveCount(0)
  await expect(dialog.locator('.timeline-step').filter({hasText:'접수 내용 수정'})).toHaveCount(1)
  record('Receipt cannot assign; AI recommendation does not assign; same-state history names the action',{})

  await dialog.getByRole('button',{name:'분류 완료',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'분류 완료',exact:true}).click()
  dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('button',{name:'배정',exact:true})).toBeVisible()
  const triaged=await get()
  assert.deepEqual([triaged.resolution_mode,triaged.cause,triaged.recurrence_risk,triaged.user_confirmed],[null,null,null,0])
  const beforeEvents=(await history()).length
  const bypass=await raw('incidents:updateStatus',{id:initial.id,status:'ASSIGNED'})
  assert.equal(bypass.ok,false);assert.match(bypass.error.message,/배정 확정/)
  assert.equal((await history()).length,beforeEvents)
  await dialog.getByRole('button',{name:'배정',exact:true}).click()
  let assignment=page.getByRole('dialog',{name:'조치부서·담당자 배정',exact:true})
  await expect(assignment.getByRole('button',{name:'배정 확정',exact:true})).toBeDisabled()
  await choose(assignment,'부대급','비행단급')
  await assignment.getByRole('combobox',{name:'소속 부대',exact:true}).fill('제19')
  await page.getByRole('option',{name:'제19전투비행단',exact:true}).click()
  await choose(assignment,'조치부서','정보통신대대')
  const contacts=await invoke('organizations:members',{unitId:'W19'})
  await choose(assignment,'담당자',`${contacts[0].rank_name} ${contacts[0].display_name} · 가상`)
  await screenshot('assignment-form')
  await assignment.getByRole('button',{name:'배정 확정',exact:true}).click()
  await expect(assignment).toHaveCount(0)
  let current=await get()
  assert.equal(current.status,'ASSIGNED');assert.equal(current.assigned_to,contacts[0].id)
  assert.equal(current.department,'가상 요청부서')
  const assigned=(await history()).filter(e=>e.event_type==='TEAM_ASSIGNED')
  assert.equal(assigned.length,1);assert.equal(assigned[0].from_status,'TRIAGED');assert.equal(assigned[0].to_status,'ASSIGNED')
  dialog=page.getByRole('dialog')
  await expect(dialog.getByText('분류 → 배정',{exact:true})).toBeVisible()
  await screenshot('assigned-detail')
  record('Classification and assignment are separate; department, person, state and history save together',{})

  await dialog.getByRole('button',{name:'배정 정보 변경',exact:true}).click()
  assignment=page.getByRole('dialog',{name:'배정 정보 변경',exact:true})
  await assignment.getByRole('button',{name:'배정 해제',exact:true}).click()
  await expect(assignment).toHaveCount(0)
  assert.deepEqual([(await get()).status,(await get()).team_id,(await get()).assigned_to],['TRIAGED',null,null])
  dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'배정',exact:true}).click()
  assignment=page.getByRole('dialog',{name:'조치부서·담당자 배정',exact:true})
  await choose(assignment,'부대급','기존 공통 정비반')
  await choose(assignment,'조치부서','유선정비반')
  await choose(assignment,'담당자',`${maintainer.rank_name} ${maintainer.display_name}`)
  await assignment.getByRole('button',{name:'배정 확정',exact:true}).click()
  await expect(assignment).toHaveCount(0)
  await invoke('incidents:applyAi',{id:initial.id,category:'기반통신',severity:'NORMAL',teamId:radio.id,rationale:'다른 부서 추천 시험',confidence:.7})
  current=await get()
  assert.equal(current.team_id,wire.id);assert.equal(current.assigned_to,maintainer.id);assert.equal(current.ai_recommended_team,radio.id)
  await invoke('incidents:assign',{id:initial.id,userId:admin.id,department:'덮어쓰기 금지'})
  assert.equal((await get()).department,'가상 요청부서')
  await invoke('incidents:assign',{id:initial.id,userId:maintainer.id})
  await dialog.getByRole('button',{name:'닫기',exact:true}).click()
  dialog=await openDetail()
  await expect(dialog.locator('.timeline-step').filter({hasText:'배정 정보 변경'})).toHaveCount(2)
  await expect(dialog.locator('.timeline-step').filter({hasText:'배정 → 배정'})).toHaveCount(0)
  record('Unassignment returns to classification; reassignment is an action; AI cannot overwrite confirmed assignment',{})

  await dialog.getByRole('button',{name:'보류',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'배정 확인 후 재개',exact:true}).click()
  await page.getByRole('dialog',{name:'배정 확인 후 재개',exact:true}).getByRole('button',{name:'배정 확정 및 재개',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'배정 확인 후 재개',exact:true})).toHaveCount(0)
  assert.equal((await get()).status,'ASSIGNED')
  await page.getByRole('dialog').getByRole('button',{name:'닫기',exact:true}).click()
  await page.getByRole('button',{name:'로그아웃',exact:true}).click()
  await login('demo_4','MAINTAINER')
  dialog=await openDetail()
  await expect(dialog.getByRole('button',{name:'배정 정보 변경',exact:true})).toHaveCount(0)
  assert.equal((await raw('incidents:assignTeam',{id:initial.id,teamId:wire.id,userId:admin.id})).ok,false)
  await dialog.getByRole('button',{name:'원격조치',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('button',{name:'조치완료',exact:true})).toBeVisible()
  assert.equal((await get()).status,'REMOTE_IN_PROGRESS')
  await dialog.getByRole('button',{name:'닫기',exact:true}).click()
  await page.getByRole('button',{name:'로그아웃',exact:true}).click()
  await login('demo_admin','ADMIN')
  const cannotUnassign=await raw('incidents:assignTeam',{id:initial.id,teamId:null,userId:null})
  assert.equal(cannotUnassign.ok,false);assert.match(cannotUnassign.error.message,/해제할 수 없습니다/)
  record('Hold resumes through assignment confirmation; assigned maintainer starts work; active work cannot be unassigned',{})

  dialog=await openDetail()
  await dialog.getByRole('button',{name:'현장출동',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'조치완료',exact:true}).click()
  let action=page.getByRole('dialog')
  await expect(action.getByRole('button',{name:'처리',exact:true})).toBeDisabled()
  await action.getByRole('textbox',{name:'장애 원인',exact:true}).fill('가상 포트 불량')
  await action.getByRole('textbox',{name:'조치 결과',exact:true}).fill('가상 포트 교체 후 정상 통신 확인')
  await action.getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('button',{name:'배정 정보 변경',exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'검증',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await screenshot('verified-history')
  // Reopened work must discard old completion/verification and confirmation markers.
  await dialog.getByRole('button',{name:'조치완료',exact:true}).click()
  action=page.getByRole('dialog')
  await action.getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'원격조치',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  let reopened=await get()
  assert.deepEqual([reopened.resolved_at,reopened.verified_at,reopened.user_confirmed],[null,null,0])
  await page.getByRole('dialog').getByRole('button',{name:'조치완료',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'검증',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'처리',exact:true}).click()
  dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'종결',exact:true}).click()
  action=page.getByRole('dialog')
  await expect(action.getByRole('button',{name:'처리',exact:true})).toBeDisabled()
  await action.getByRole('checkbox',{name:'요청부서 사용자 확인 완료',exact:true}).check()
  await action.getByRole('button',{name:'처리',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  current=await get()
  assert.equal((await raw('incidents:assignTeam',{id:initial.id,teamId:wire.id,userId:admin.id})).ok,false)
  assert.equal(current.status,'CLOSED');assert.equal(current.user_confirmed,1);assert.equal(current.resolution_mode,'REMOTE')
  record('Remote → on-site → resolution with result → verification → user-confirmed closure',{})
  assert.deepEqual(errors,[])
  console.log(`Incident workflow E2E passed. Evidence: ${dataDir}`)
} catch(error) {
  if(page) await page.screenshot({path:resolve(dataDir,'failure.png'),animations:'disabled'}).catch(()=>{})
  throw error
} finally {
  writeFileSync(resolve(dataDir,'checks.json'),JSON.stringify({checks,errors},null,2))
  await app.close()
}
